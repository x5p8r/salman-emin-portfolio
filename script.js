function applyLanguage(language) {
  const dictionary = translations[language];
  if (!dictionary) return;

  localStorage.setItem("se-language", language);
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.body.dir = document.documentElement.dir;
  document.title = pageTitles[language][page] || pageTitles[language].home;
  const description = $('meta[name="description"]');
  if (description) {
    description.content = language === "en"
      ? "Salman Emin — software engineer and digital creator building useful tools and thoughtful interfaces."
      : "سلمان أمين — مهندس برمجيات ومبدع رقمي يبني أدوات مفيدة وواجهات مدروسة.";
  }
  if (languageButton) {
    languageButton.textContent = language === "en" ? "عربي ↗" : "English ↗";
    languageButton.setAttribute("aria-label", language === "en" ? "Switch to Arabic" : "Switch to English");
  }
  if (menuToggle) {
    const menuState = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-label", language === "en"
      ? (menuState ? "Close menu" : "Open menu")
      : (menuState ? "إغلاق القائمة" : "فتح القائمة"));
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = dictionary[element.dataset.i18nHtml];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAriaLabel];
    if (value !== undefined) {
      element.setAttribute("aria-label", value);
      if (element.hasAttribute("title")) element.setAttribute("title", value);
    }
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute("alt", value);
  });

  const navKeys = {
    home: "navHome", work: "navWork", expertise: "navExpertise", about: "navAbout", contact: "navContact"
  };
  navigation?.querySelectorAll(".nav-link").forEach((link) => {
    const key = Object.keys(navKeys).find((name) => link.getAttribute("href") === `${name === "home" ? "index" : name}.html`);
    if (key === page) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
}

