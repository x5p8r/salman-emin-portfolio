const skillVertexButtons = [...document.querySelectorAll("[data-skill-select]")];
const skillDetailPanel = $("#skillDetailPanel");
let skillPanelTimer;

function updateSkillPanel(skill) {
  const details = translations[currentLanguage].skillDetails[skill];
  if (!skillDetailPanel || !details) return;
  $("#skillDetailCounter").textContent = details.counter;
  $("#skillDetailTitle").textContent = details.title;
  $("#skillDetailDescription").textContent = details.description;
  ["#skillDetailItem1", "#skillDetailItem2", "#skillDetailItem3"].forEach((selector, index) => {
    $(selector).textContent = details.details[index];
  });
  skillDetailPanel.dataset.skill = skill;
}

function selectSkillVertex(skill, animate = true) {
  const selectedButton = skillVertexButtons.find((button) => button.dataset.skillSelect === skill);
  if (!selectedButton) return;
  activeSkillVertex = skill;
  $(".skill-triangle")?.setAttribute("data-active", skill);
  skillVertexButtons.forEach((button) => {
    const selected = button === selectedButton;
    button.classList.toggle("is-selected", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
  clearTimeout(skillPanelTimer);
  if (!animate || matchMedia("(prefers-reduced-motion: reduce)").matches) {
    skillDetailPanel?.classList.remove("is-exiting", "is-entering");
    updateSkillPanel(skill);
    return;
  }
  skillDetailPanel?.classList.remove("is-entering");
  skillDetailPanel?.classList.add("is-exiting");
  skillPanelTimer = window.setTimeout(() => {
    updateSkillPanel(activeSkillVertex);
    skillDetailPanel?.classList.remove("is-exiting");
    skillDetailPanel?.classList.add("is-entering");
    requestAnimationFrame(() => requestAnimationFrame(() => skillDetailPanel?.classList.remove("is-entering")));
  }, 220);
}
skillVertexButtons.forEach((button) => {
  button.addEventListener("click", () => selectSkillVertex(button.dataset.skillSelect));
});
selectSkillVertex(activeSkillVertex, false);
